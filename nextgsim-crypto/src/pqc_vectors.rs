//! Post-quantum known-answer vectors (FIPS 203 / FIPS 204), with provenance.
//!
//! GENERATED-BY-HAND-ONCE, then frozen: every constant below was transcribed
//! from an external, authoritative vector file, never from this crate's own
//! output. That distinction is the whole point of the module. A "known answer"
//! recorded from our own implementation would be a round-trip test wearing a
//! KAT's clothes: it would pass even if our byte encodings disagreed with the
//! standard, which is precisely the risk worth covering while `ml-kem` and
//! `ml-dsa` are pre-1.0 release candidates.
//!
//! # Sources
//!
//! 1. **NIST ACVP ML-KEM (FIPS 203)** -- `gen-val/json-files/ML-KEM-keyGen-FIPS203/`
//!    and `.../ML-KEM-encapDecap-FIPS203/internalProjection.json` from
//!    <https://github.com/usnistgov/ACVP-Server> at commit
//!    `65370b861b96efd30dfe0daae607bde26a78a5c8` ("65370b8"). That is the same
//!    commit the `ml-kem` crate's own `tests/README.md` pins, so our constants and
//!    the upstream crate's ACVP harness answer to one authority. (The `ml-kem`
//!    crate excludes those JSON files from its published artifact -- only the
//!    README survives packaging -- which is why the bytes are transcribed here.)
//!
//! 2. **NIST ACVP ML-DSA (FIPS 204)** -- `.../ML-DSA-keyGen-FIPS204/internalProjection.json`
//!    at the same commit `65370b8` (the pin in the `ml-dsa` crate's `tests/README.md`),
//!    and `.../ML-DSA-sigGen-FIPS204/internalProjection.json` at commit
//!    `975de31eb83d87039ec88934fdc47d8c312b892d` ("975de31"). The newer commit is
//!    required for the signature vectors and only for them: at `65370b8` the sigGen
//!    and sigVer groups predate the `signatureInterface` / `preHash` / `context`
//!    fields, so they describe only ML-DSA.Sign_internal (FIPS 204 Algorithm 7),
//!    which has no domain separator. [`crate::pqc_sign::ml_dsa_verify`] implements
//!    the EXTERNAL interface (Algorithm 3, pure, empty context), so it can only be
//!    held to groups that declare themselves external -- a distinction that exists
//!    only in the later files.
//!
//! 3. **IETF LAMPS dilithium-certificates examples** -- `examples/ML-DSA-44.pub`
//!    from <https://github.com/lamps-wg/dilithium-certificates>, as vendored at
//!    `tests/examples/` in `ml-dsa 0.1.0-rc.7`. Used as an INDEPENDENT second
//!    authority for ML-DSA-44 key generation: the LAMPS example derives its key
//!    from the seed `00 01 02 ... 1f` with a different implementation (CIRCL, via
//!    `examples/generate.go`) than ACVP's. Two independent computations agreeing
//!    rules out both an implementation bug and a transcription error -- the same
//!    reasoning [`crate::eap_aka_prime`] records for its RFC 9048 vectors.
//!
//! 4. **RFC 7748 §6.1** -- the Curve25519 X25519 test vector, for the classical
//!    leg of the hybrid KEM.
//!
//! # Byte layouts
//!
//! ML-KEM `ek`/`dk` are FIPS 203 §7.1-7.2 `ByteEncode`d keys, matching
//! `ml_kem::EncodedSizeUser::as_bytes`. ML-DSA `pk` is FIPS 204 Algorithm 22
//! `pkEncode` output, matching `ml_dsa::VerifyingKey::encode`. ML-DSA `sig` is
//! Algorithm 26 `sigEncode` output, matching `ml_dsa::Signature::encode`.
//!
//! # Why a separate module rather than inline in each `mod tests`
//!
//! `nea.rs`/`nia.rs`/`snow3g.rs` inline their 3GPP constants because those are
//! 16-byte keys and 100-byte payloads. A single ML-DSA-87 verifying key is 2592
//! bytes and a signature 4627; inlining the set would bury the assertions it
//! serves. The house pattern that matters -- hex constants with the source cited
//! per constant, never a captured implementation output -- is preserved.
//!
//! # Why extracted constants rather than vendored JSON
//!
//! The alternative considered and rejected was vendoring the ACVP
//! internal-projection files wholesale (e.g. under `tools/acvp/`): ~1.4 MB for the
//! two ML-KEM files alone, ~2.6 MB with ML-DSA, plus a `serde_json` parser in the
//! test path and a runtime dependency on files being present at a relative path.
//! Against that, this module is ~124 KB and needs no parser.
//!
//! The deciding argument is not size but what a reader can check. A vendored blob
//! gives 180 test cases nobody reads and one README-level citation; extraction
//! forces a per-constant citation naming the file, the `tgId`, the `tcId` and the
//! commit, so any single expected byte string can be traced to its origin without
//! leaving the file. Wholesale vendoring would also set a precedent for how this
//! repo carries external test data, which is a larger decision than a
//! test-coverage change should make. (`tools/` does vendor multi-megabyte 3GPP
//! ASN.1 schemas, but those are code-generator INPUT, consumed by build scripts --
//! not test data.)
//!
//! The cost is honest: coverage is a deliberate subset, not all 180 ACVP cases.
//! The subset is chosen for span rather than volume -- every parameter set of every
//! operation, plus the implicit-rejection branch -- on the reasoning that a
//! byte-encoding or algorithm error shows up in the first case of a parameter set,
//! not in the twenty-fifth. Broad ACVP sweeps are the upstream crates' job, and
//! both `ml-kem` and `ml-dsa` run them against these same files.
//!
//! # Reproducing these constants
//!
//! ```text
//! gh api "repos/usnistgov/ACVP-Server/contents/gen-val/json-files/\
//! ML-KEM-keyGen-FIPS203/internalProjection.json?ref=65370b861b96efd30dfe0daae607bde26a78a5c8" \
//!   -H "Accept: application/vnd.github.raw" > keygen.json
//! ```
//!
//! then read `.testGroups[] | select(.parameterSet == "ML-KEM-512") | .tests[0]`.
//! The ML-DSA signature constants use the same call with the `975de31` ref and
//! `ML-DSA-sigGen-FIPS204`, selecting the group whose `signatureInterface` is
//! `external`, `preHash` is `pure` and `externalMu` is false, then the test whose
//! `context` is empty.

#![allow(clippy::unreadable_literal, reason = "hex vector constants")]

/// Decode an upper- or lower-case hex string into bytes.
///
/// Panics on malformed input, which in a vector module means a transcription
/// error: failing loudly at the first assertion is the correct response.
pub fn unhex(s: &str) -> Vec<u8> {
    assert!(
        s.len().is_multiple_of(2),
        "hex string has odd length: {}",
        s.len()
    );
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).expect("vector constant is valid hex"))
        .collect()
}

/// Decode a 32-byte hex constant into a fixed-size array.
pub fn unhex32(s: &str) -> [u8; 32] {
    unhex(s)
        .try_into()
        .expect("vector constant is exactly 32 bytes")
}

